// Publishes the Tailwind-built CSS (styles/recipe.gen.css) as a content-hashed, immutable static
// asset under public/assets so Vercel's CDN + the browser cache it across every recipe page, and
// writes its href into a TS module the SSR page links. Regenerate via `npm run build:styles`;
// do not hand-edit the outputs.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const css = readFileSync(root + "styles/recipe.gen.css", "utf8");
const hash = createHash("sha256").update(css).digest("hex").slice(0, 8);

const dir = root + "public/assets";
mkdirSync(dir, { recursive: true });
for (const f of readdirSync(dir)) if (/^recipe\.[0-9a-f]+\.css$/.test(f)) rmSync(dir + "/" + f);

const file = `recipe.${hash}.css`;
writeFileSync(dir + "/" + file, css);
const href = `/assets/${file}`;
writeFileSync(
  root + "src/recipe-page.styles.ts",
  `// GENERATED by scripts/publish-recipe-css.mjs — do not edit. Run \`npm run build:styles\`.\nexport const RECIPE_CSS_HREF = ${JSON.stringify(href)};\n`,
);
console.log(`[styles] published public${href} (${css.length} bytes)`);
